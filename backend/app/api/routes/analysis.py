import io
import os
import hashlib
from fastapi import APIRouter, UploadFile, File, Form, HTTPException, status
from typing import Optional
import numpy as np
from PIL import Image
try:
    import tifffile
except ImportError:
    tifffile = None

from app.core.config import settings
from app.services.flood_model import flood_model_service
from verification.verifier import VERIFIED_TOKENS
from verification.integrity import compute_sha256

router = APIRouter(tags=["Analysis"])

@router.post("/analyze", status_code=status.HTTP_200_OK)
async def analyze_flood_raster(
    file: UploadFile = File(...),
    verification_id: Optional[str] = Form(None),
    threshold: Optional[float] = Form(0.50)
):
    """
    Executes real U-Net flood segmentation on strictly verified satellite rasters.
    Fails closed if verification_id is missing, invalid, or if model checkpoint is missing.
    """
    if not verification_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={
                "error": "VERIFICATION_REQUIRED",
                "message": "Image must pass server-side verification (/api/verify-image) before flood inference."
            }
        )

    if verification_id not in VERIFIED_TOKENS:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={
                "error": "INVALID_VERIFICATION_TOKEN",
                "message": f"Verification token '{verification_id}' is expired, invalid, or was not generated by this server."
            }
        )

    verified_record = VERIFIED_TOKENS[verification_id]
    verification_status = verified_record["result"]["status"]
    geo_meta = verified_record.get("geo_meta") or {}

    if verification_status != "VERIFIED_SATELLITE_INPUT":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={
                "error": "PROVENANCE_UNVERIFIED",
                "message": f"Inference blocked: Verification status is '{verification_status}'. Only 'VERIFIED_SATELLITE_INPUT' can enter flood model inference."
            }
        )

    # Read uploaded file contents and verify hash against verified token
    try:
        contents = await file.read()
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": "PAYLOAD_READ_ERROR", "message": f"Failed to read file: {str(e)}"}
        )

    if len(contents) > settings.MAX_UPLOAD_SIZE_MB * 1024 * 1024:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail={
                "error": "PAYLOAD_TOO_LARGE",
                "message": f"Uploaded file exceeds {settings.MAX_UPLOAD_SIZE_MB}MB limit."
            }
        )

    uploaded_hash = compute_sha256(contents)
    if uploaded_hash != verified_record["file_hash"]:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "error": "FILE_HASH_MISMATCH",
                "message": "The uploaded file contents do not match the byte signature verified in token."
            }
        )

    # Check model checkpoint availability
    if not flood_model_service.is_available():
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={
                "error": "FLOOD_MODEL_UNAVAILABLE",
                "message": "No trained FloodSight segmentation checkpoint is installed."
            }
        )

    # Decode raster into numpy array
    try:
        safe_name = os.path.basename(verified_record.get("filename", "raster.tif"))
        if safe_name.lower().endswith(('.tif', '.tiff')) and tifffile is not None:
            try:
                arr = tifffile.imread(io.BytesIO(contents))
            except Exception:
                img = Image.open(io.BytesIO(contents))
                arr = np.array(img)
        else:
            img = Image.open(io.BytesIO(contents))
            arr = np.array(img)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": "DECODE_ERROR", "message": f"Failed to decode raster array: {str(e)}"}
        )

    # Convert raster using explicit validated conversion pipeline to exact (H, W, 3) contract
    from verification.conversion import SentinelBandConversionPipeline
    try:
        arr_3channel, conversion_rule = SentinelBandConversionPipeline.convert_to_model_input(
            arr=arr,
            geo_meta=geo_meta
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail={
                "error": "CONVERSION_PIPELINE_ERROR",
                "message": f"Input raster failed validated conversion pipeline: {str(e)}"
            }
        )

    # Execute real prediction with FloodSegmenter
    try:
        prediction = flood_model_service.predict(arr=arr_3channel, threshold=threshold, geo_meta=geo_meta)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": "INFERENCE_ERROR", "message": f"Flood model execution error: {str(e)}"}
        )

    return {
        "status": "SUCCESS",
        "analysis_id": verification_id,
        "verification_id": verification_id,
        "filename": verified_record["filename"],
        "flood_detected": prediction["flood_detected"],
        "flood_pixel_count": prediction["flood_pixel_count"],
        "valid_pixel_count": prediction.get("valid_pixel_count", prediction["total_pixels"]),
        "total_pixels": prediction["total_pixels"],
        "flooded_pixel_fraction": prediction.get("flooded_pixel_fraction", prediction["coverage_percent"] / 100.0),
        "coverage_percent": prediction["coverage_percent"],
        "confidence_mean": prediction["confidence_mean"],
        "connected_regions": prediction["connected_regions"],
        "physical_area_ha": prediction["physical_area_ha"],
        "physical_area_notes": prediction["physical_area_notes"],
        "area_calculation_method": prediction.get("area_calculation_method", "NOT_CALCULATED"),
        "spatial_resolution_m": prediction.get("spatial_resolution_m"),
        "geospatial_validity": prediction.get("geospatial_validity", False),
        "inference_latency_ms": prediction["inference_latency_ms"],
        "threshold_used": threshold,
        "created_at": verified_record["timestamp"]
    }
